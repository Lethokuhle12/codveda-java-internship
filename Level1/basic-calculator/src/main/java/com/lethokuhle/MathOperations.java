package com.lethokuhle;

public class MathOperations {

    public MathOperations() {
    }

    public double add(double firstNumber, double secNumber) {

        return firstNumber + secNumber;

    }

    public double subtract(double firstNumber, double secNumber) {

        return firstNumber - secNumber;

    }

    public double multiply(double firstNumber, double secNumber) {

        return firstNumber * secNumber;

    }

    public double divide(double firstNumber, double secNumber) {

        return firstNumber / secNumber;

    }

}
